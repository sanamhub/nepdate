"""Catalogue of C# NepDate's own unit tests (hub task H5).

Reads every *.cs file under tests/NepDate.Tests/ of a NepDate clone and writes
spec/vectors/csharp-tests/catalog.tsv: one row per [Fact] and one row per
[InlineData] of a [Theory]. Ports implement the rows of each phase as tests
named after the row id (spec/PORT-PLAN.md, "C# test catalogue").

The phase column comes from tools/csharp_tests_phase.tsv (first matching
pattern wins). A row with no matching pattern fails the tool, so a new upstream
test can't slip in without a reviewed phase.

Usage:
    py tools/catalog_csharp_tests.py <path-to-NepDate-repo>          # write
    py tools/catalog_csharp_tests.py <path-to-NepDate-repo> --check  # exit 1 if different
"""

from __future__ import annotations

import argparse
import fnmatch
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "spec" / "vectors" / "csharp-tests" / "catalog.tsv"
PHASES = ROOT / "tools" / "csharp_tests_phase.tsv"
TESTS_DIR = Path("tests/NepDate.Tests")
HEADER = ["id", "file", "method", "data", "asserts", "phase"]

FACT = re.compile(r"^\s*\[Fact\b")
THEORY = re.compile(r"^\s*\[Theory\b")
INLINE = re.compile(r"^\s*\[InlineData\((.*)\)\]")
METHOD = re.compile(r"^\s*public\s+(?:async\s+)?[\w<>\[\],\s]+?\s+(\w+)\s*\(")
ASSERT = re.compile(r"\bAssert\.")


def clean(text: str, limit: int) -> str:
    text = re.sub(r"\s+", " ", text.replace("\t", " ")).strip()
    return text[:limit]


def strip_comment(line: str) -> str:
    """Drop a trailing // comment that sits outside string literals."""
    in_str = False
    for i, ch in enumerate(line):
        if ch == '"' and (i == 0 or line[i - 1] != "\\"):
            in_str = not in_str
        elif not in_str and line.startswith("//", i):
            return line[:i]
    return line


def first_assert(lines: list[str], start: int) -> str:
    depth = 0
    seen_body = False
    for line in lines[start:]:
        if ASSERT.search(line):
            return clean(line, 200)
        depth += line.count("{") - line.count("}")
        seen_body = seen_body or "{" in line
        if seen_body and depth <= 0:
            break
    return ""


def scan_file(path: Path, rel: str) -> list[dict]:
    lines = path.read_text(encoding="utf-8-sig").splitlines()
    rows: list[dict] = []
    pending_fact = False
    pending_data: list[str] = []
    in_theory = False
    for i, line in enumerate(lines):
        if FACT.match(line):
            pending_fact = True
            continue
        if THEORY.match(line):
            in_theory = True
            continue
        m = INLINE.match(strip_comment(line).rstrip())
        if m and in_theory:
            pending_data.append(clean(m.group(1), 500))
            continue
        if not (pending_fact or in_theory):
            continue
        m = METHOD.match(line)
        if not m:
            continue
        method = m.group(1)
        stem = Path(rel).stem
        asserts = first_assert(lines, i)
        if pending_fact:
            rows.append({"id": f"{stem}.{method}", "file": rel, "method": method,
                         "data": "", "asserts": asserts})
        if in_theory:
            if not pending_data:
                raise SystemExit(f"{rel}:{i + 1}: [Theory] {method} has no [InlineData]")
            for n, data in enumerate(pending_data, 1):
                rows.append({"id": f"{stem}.{method}#{n}", "file": rel, "method": method,
                             "data": data, "asserts": asserts})
        pending_fact = False
        in_theory = False
        pending_data = []
    return rows


def load_phases() -> list[tuple[str, str]]:
    rules = []
    for line in PHASES.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        pattern, phase = line.split("\t")[:2]
        rules.append((pattern.strip(), phase.strip()))
    return rules


def render(rows: list[dict], commit: str) -> str:
    out = [f"# C# NepDate tests at {commit}; generated by tools/catalog_csharp_tests.py, do not edit",
           "\t".join(HEADER)]
    for r in rows:
        out.append("\t".join(r[h] for h in HEADER))
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("repo", type=Path)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    tests = args.repo / TESTS_DIR
    commit = subprocess.run(["git", "-C", str(args.repo), "rev-parse", "--short=8", "HEAD"],
                            capture_output=True, text=True, check=True).stdout.strip()
    rows: list[dict] = []
    for path in sorted(tests.rglob("*.cs")):
        rows.extend(scan_file(path, path.relative_to(tests).as_posix()))

    rules = load_phases()
    unmapped = []
    for r in rows:
        key = f"{r['file']}:{r['method']}"
        r["phase"] = next((p for pat, p in rules if fnmatch.fnmatchcase(key, pat)), "")
        if not r["phase"]:
            unmapped.append(key)
    if unmapped:
        for key in sorted(set(unmapped)):
            print(f"no phase for {key}", file=sys.stderr)
        return 1

    ids = [r["id"] for r in rows]
    dupes = sorted({x for x in ids if ids.count(x) > 1})
    if dupes:
        print("duplicate ids: " + ", ".join(dupes), file=sys.stderr)
        return 1

    facts = sum(1 for r in rows if not r["data"])
    print(f"{len(rows)} rows ({facts} [Fact], {len(rows) - facts} [InlineData]) at {commit}")
    text = render(rows, commit)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
